/* ==========================================================================
   officer-dashboard.js — faculty officer: review, batch approval, scheduling
   --------------------------------------------------------------------------
   All approvals here are MOCK actions that change demo state in the browser.
   In production each action is a request to the backend, which must:
     - confirm the caller is an authorized faculty officer,
     - re-check payment with the official portal,
     - generate the unique verification token,
     - write the audit-log entry itself.
   ========================================================================== */

document.addEventListener('DOMContentLoaded', function () {
  'use strict';

  // Administrators may also open this page (supervision).
  var session = App.requireRole(['officer', 'admin']);
  if (!session) return;
  App.renderShell('officer-dashboard.html');

  var h = App.escapeHtml;
  var PAGE_SIZE = 10;
  var page = 1;
  var selected = {}; // student id -> true
  var filters = { q: '', level: 'all', status: 'all', fee: 'all' };

  /* ---- Helpers --------------------------------------------------------------- */
  function allRequests() {
    return App.state.students.filter(function (s) { return s.request.status !== 'none'; });
  }
  // A request can be batch-approved only if it is pending AND fully paid.
  function isEligible(student) {
    return student.request.status === 'pending' && student.feeStatus === 'paid';
  }
  function filteredRequests() {
    var q = filters.q.trim().toLowerCase();
    return allRequests().filter(function (s) {
      if (q && s.name.toLowerCase().indexOf(q) === -1 && s.matric.toLowerCase().indexOf(q) === -1) return false;
      if (filters.level !== 'all' && String(s.level) !== filters.level) return false;
      if (filters.status !== 'all' && App.effectiveStatus(s) !== filters.status) return false;
      if (filters.fee !== 'all' && s.feeStatus !== filters.fee) return false;
      return true;
    }).sort(function (a, b) { return a.request.submittedAt < b.request.submittedAt ? 1 : -1; });
  }
  function selectedIds() {
    // Drop anything that is no longer eligible (for example, already approved).
    return Object.keys(selected).filter(function (id) {
      var s = App.findStudent(id);
      return s && isEligible(s);
    });
  }

  /* ---- Mock actions ------------------------------------------------------------ */
  function approve(student) {
    student.request.status = 'approved';
    student.request.decidedAt = new Date().toISOString();
    student.request.decidedBy = session.name;
    student.request.note = '';
    student.clearance.issuedAt = student.request.decidedAt;
    student.clearance.revoked = false;
    student.clearance.revokedAt = null;
    student.clearance.revokeReason = '';
    // Placeholder reference only. The real token is generated by the backend.
    student.clearance.ref = AAUA_DATA.randomRef();
    delete selected[student.id];
  }

  /* ---- Stats --------------------------------------------------------------------- */
  function renderStats() {
    var requests = allRequests();
    function count(fn) { return requests.filter(fn).length; }
    var tiles = [
      ['Pending review', count(function (s) { return s.request.status === 'pending'; }), 'gold', 'Awaiting a decision'],
      ['Eligible for batch approval', count(isEligible), '', 'Pending with full payment'],
      ['Approved', count(function (s) { return App.effectiveStatus(s) === 'approved'; }), 'green', 'Clearance issued'],
      ['Needs review', count(function (s) { return s.request.status === 'needs_review'; }), 'amber', 'Returned to student']
    ];
    document.getElementById('officer-stats').innerHTML = tiles.map(function (t) {
      return '<div class="stat ' + t[2] + '"><div class="stat-label">' + t[0] + '</div><div class="stat-value">' + t[1] + '</div><div class="stat-note">' + t[3] + '</div></div>';
    }).join('');
  }

  /* ---- Request table --------------------------------------------------------------- */
  function renderTable() {
    var list = filteredRequests();
    var info = App.paginate(list, page, PAGE_SIZE);
    page = info.page;

    var rows = info.items.map(function (s) {
      var eligible = isEligible(s);
      var checkbox = eligible
        ? '<input type="checkbox" data-select="' + s.id + '"' + (selected[s.id] ? ' checked' : '') + ' aria-label="Select ' + h(s.name) + '">'
        : '<input type="checkbox" disabled aria-label="' + h(s.name) + ' is not eligible for batch approval" title="Not eligible for batch approval">';
      return '<tr>' +
        '<td data-label="Select">' + checkbox + '</td>' +
        '<td data-label="Student"><div class="cell-stack"><strong>' + h(s.name) + '</strong><span class="mono muted">' + h(s.matric) + '</span></div></td>' +
        '<td data-label="Department / Faculty"><div class="cell-stack"><span>' + h(s.department) + '</span><span class="muted">' + h(s.faculty) + '</span></div></td>' +
        '<td data-label="Level">' + s.level + '</td>' +
        '<td data-label="Payment">' + App.feeBadge(s.feeStatus) + '</td>' +
        '<td data-label="Status">' + App.statusBadge(App.effectiveStatus(s)) + '</td>' +
        '<td data-label="Submitted" class="nowrap">' + App.fmtDate(s.request.submittedAt) + '</td>' +
        '<td data-label="Action"><button type="button" class="btn btn-outline btn-sm" data-review="' + s.id + '">Review</button></td>' +
        '</tr>';
    }).join('');

    document.getElementById('request-rows').innerHTML = rows ||
      '<tr><td colspan="8" class="empty-cell"><div class="empty-state"><strong>No requests match your search</strong>Try a different name, matric number or filter.</div></td></tr>';

    App.renderPager(document.getElementById('request-pager'), info, function (newPage) { page = newPage; renderTable(); });

    // Header checkbox reflects the eligible rows on this page
    var pageEligible = info.items.filter(isEligible);
    var pageBox = document.getElementById('select-page');
    pageBox.disabled = pageEligible.length === 0;
    pageBox.checked = pageEligible.length > 0 && pageEligible.every(function (s) { return selected[s.id]; });

    // Batch bar
    var ids = selectedIds();
    var eligibleInFilter = list.filter(isEligible).length;
    document.getElementById('selected-count').textContent = ids.length + ' selected';
    document.getElementById('eligible-note').textContent = ' · ' + eligibleInFilter + ' eligible in current results';
    document.getElementById('batch-approve').disabled = ids.length === 0;
    document.getElementById('batch-approve').textContent = ids.length ? 'Approve selected (' + ids.length + ')' : 'Approve selected';
    document.getElementById('batch-bar').classList.toggle('has-selection', ids.length > 0);
    document.getElementById('select-all-eligible').disabled = eligibleInFilter === 0;
  }

  function renderAll() { renderStats(); renderTable(); }

  /* ---- Filters ------------------------------------------------------------------------ */
  function readFilters() {
    filters.q = document.getElementById('search').value;
    filters.level = document.getElementById('filter-level').value;
    filters.status = document.getElementById('filter-status').value;
    filters.fee = document.getElementById('filter-fee').value;
    page = 1;
    renderTable();
  }
  var filterForm = document.getElementById('filters');
  filterForm.addEventListener('input', readFilters);
  filterForm.addEventListener('submit', function (event) { event.preventDefault(); });
  filterForm.addEventListener('reset', function () { setTimeout(readFilters, 0); });

  /* ---- Selection ------------------------------------------------------------------------ */
  document.getElementById('request-rows').addEventListener('change', function (event) {
    var id = event.target.dataset.select;
    if (!id) return;
    if (event.target.checked) selected[id] = true; else delete selected[id];
    renderTable();
  });
  document.getElementById('select-page').addEventListener('change', function (event) {
    var info = App.paginate(filteredRequests(), page, PAGE_SIZE);
    info.items.filter(isEligible).forEach(function (s) {
      if (event.target.checked) selected[s.id] = true; else delete selected[s.id];
    });
    renderTable();
  });
  document.getElementById('select-all-eligible').addEventListener('click', function () {
    filteredRequests().filter(isEligible).forEach(function (s) { selected[s.id] = true; });
    renderTable();
  });
  document.getElementById('clear-selection').addEventListener('click', function () {
    selected = {};
    renderTable();
  });

  /* ---- Batch approval ------------------------------------------------------------------- */
  var batchConfirm = document.getElementById('batch-confirm');
  var batchButton = document.getElementById('batch-confirm-button');

  document.getElementById('batch-approve').addEventListener('click', function () {
    var ids = selectedIds();
    if (!ids.length) return;
    document.getElementById('batch-summary').textContent =
      'You are about to approve ' + ids.length + ' clearance request' + (ids.length === 1 ? '' : 's') + '. A clearance document will be issued to each student.';
    document.getElementById('batch-list').innerHTML = ids.map(function (id) {
      var s = App.findStudent(id);
      return '<tr><td data-label="Student">' + h(s.name) + '</td><td data-label="Matric" class="mono">' + h(s.matric) + '</td><td data-label="Level">' + s.level + ' Level</td></tr>';
    }).join('');
    batchConfirm.checked = false;
    batchButton.disabled = true;
    App.openModal('batch-modal');
  });
  batchConfirm.addEventListener('change', function () { batchButton.disabled = !batchConfirm.checked; });
  batchButton.addEventListener('click', function () {
    var ids = selectedIds();
    ids.forEach(function (id) {
      var s = App.findStudent(id);
      approve(s);
      App.audit('Clearance approved (batch)', s.matric, 'Batch of ' + ids.length, s.id);
    });
    App.save();
    selected = {};
    App.closeModal('batch-modal');
    renderAll();
    App.toast(ids.length + ' request' + (ids.length === 1 ? '' : 's') + ' approved.', 'success');
  });

  /* ---- Review a single request ------------------------------------------------------------ */
  var reviewing = null;

  function openReview(id) {
    reviewing = App.findStudent(id);
    if (!reviewing) return;
    var s = reviewing;
    var status = App.effectiveStatus(s);
    var docs = s.request.docs || {};

    document.getElementById('review-body').innerHTML =
      '<dl class="details">' +
        '<div><dt>Student name</dt><dd>' + h(s.name) + '</dd></div>' +
        '<div><dt>Matric number</dt><dd class="mono">' + h(s.matric) + '</dd></div>' +
        '<div><dt>Department</dt><dd>' + h(s.department) + '</dd></div>' +
        '<div><dt>Faculty</dt><dd>' + h(s.faculty) + '</dd></div>' +
        '<div><dt>Level</dt><dd>' + s.level + ' Level</dd></div>' +
        '<div><dt>Payment status</dt><dd>' + App.feeBadge(s.feeStatus) + '</dd></div>' +
        '<div><dt>Request status</dt><dd>' + App.statusBadge(status) + '</dd></div>' +
        '<div><dt>Submitted</dt><dd>' + App.fmtDateTime(s.request.submittedAt) + '</dd></div>' +
        (s.request.decidedAt ? '<div><dt>Last decision</dt><dd>' + App.fmtDateTime(s.request.decidedAt) + ' · ' + h(s.request.decidedBy) + '</dd></div>' : '') +
      '</dl>' +
      '<h3 style="margin-top:18px">Submitted documents</h3>' +
      '<ul class="checklist small">' +
        '<li>School-fee receipt — <span class="mono">' + h(docs.receipt || 'not provided') + '</span></li>' +
        '<li>Passport photograph — <span class="mono">' + h(docs.photo || 'not provided') + '</span></li>' +
        '<li>Student ID card (' + s.level + ' Level) — <span class="mono">' + h(docs.idcard || 'not provided') + '</span></li>' +
      '</ul>' +
      (s.request.note ? '<div class="alert warning"><span class="alert-icon" aria-hidden="true">!</span><p><strong>Current note to student:</strong> ' + h(s.request.note) + '</p></div>' : '') +
      (status === 'revoked' ? '<div class="alert danger"><span class="alert-icon" aria-hidden="true">&times;</span><p><strong>Revoked:</strong> ' + h(s.clearance.revokeReason) + '</p></div>' : '') +
      (s.feeStatus !== 'paid' && status !== 'approved' ? '<div class="alert danger" style="margin-top:12px"><span class="alert-icon" aria-hidden="true">&times;</span><p>This student cannot be approved because full payment is not on record.</p></div>' : '') +
      '<div class="form-field" style="margin:16px 0 0">' +
        '<label for="review-note">Note to student <span class="muted small">(required to reject, return for review or revoke)</span></label>' +
        '<textarea class="input" id="review-note" maxlength="300" aria-describedby="review-note-error"></textarea>' +
        '<p class="field-error" id="review-note-error" hidden></p>' +
      '</div>';

    // Which buttons make sense depends on the current status
    var buttons = '<button type="button" class="btn btn-outline" data-close-modal>Close</button>';
    if (status === 'approved') {
      buttons += '<a class="btn btn-outline" href="clearance-preview.html?student=' + s.id + '">View document</a>' +
        '<button type="button" class="btn btn-danger" data-decision="revoke">Revoke clearance</button>';
    } else if (status === 'revoked') {
      buttons += '<a class="btn btn-outline" href="clearance-preview.html?student=' + s.id + '">View document</a>';
    } else {
      buttons += '<button type="button" class="btn btn-danger" data-decision="reject">Reject</button>' +
        '<button type="button" class="btn btn-outline" data-decision="needs_review">Needs review</button>' +
        '<button type="button" class="btn btn-gold" data-decision="approve"' + (s.feeStatus === 'paid' ? '' : ' disabled') + '>Approve</button>';
    }
    document.getElementById('review-actions').innerHTML = buttons;
    App.openModal('review-modal');
  }

  document.getElementById('request-rows').addEventListener('click', function (event) {
    var button = event.target.closest('[data-review]');
    if (button) openReview(button.dataset.review);
  });

  document.getElementById('review-actions').addEventListener('click', function (event) {
    var button = event.target.closest('[data-decision]');
    if (!button || !reviewing) return;
    var decision = button.dataset.decision;
    var noteInput = document.getElementById('review-note');
    var note = noteInput.value.trim();
    var s = reviewing;

    if (decision !== 'approve' && !note) {
      App.setFieldError(noteInput, 'Add a short note explaining this decision to the student.');
      noteInput.focus();
      return;
    }

    var now = new Date().toISOString();
    if (decision === 'approve') {
      if (s.feeStatus !== 'paid') return; // never approve without full payment
      approve(s);
      App.audit('Clearance approved', s.matric, 'Clearance document issued', s.id);
      App.toast('Clearance approved for ' + s.name + '.', 'success');
    } else if (decision === 'needs_review' || decision === 'reject') {
      s.request.status = decision === 'reject' ? 'rejected' : 'needs_review';
      s.request.decidedAt = now;
      s.request.decidedBy = session.name;
      s.request.note = note;
      delete selected[s.id];
      App.audit(decision === 'reject' ? 'Clearance request rejected' : 'Marked as needs review', s.matric, note, s.id);
      App.toast(decision === 'reject' ? 'Request rejected.' : 'Request returned to the student for review.');
    } else if (decision === 'revoke') {
      s.clearance.revoked = true;
      s.clearance.revokedAt = now;
      s.clearance.revokeReason = note;
      App.audit('Clearance revoked', s.matric, note, s.id);
      App.toast('Clearance revoked for ' + s.name + '.', 'danger');
    }
    App.save();
    App.closeModal('review-modal');
    renderAll();
  });

  /* ---- Clearance windows (scheduling) ------------------------------------------------------- */
  var windowFields = {
    title: document.getElementById('window-title'),
    level: document.getElementById('window-level'),
    opens: document.getElementById('window-opens'),
    closes: document.getElementById('window-closes'),
    deadline: document.getElementById('window-deadline')
  };

  function renderWindows() {
    var labels = { open: ['Open now', 'success'], upcoming: ['Upcoming', 'info'], closed: ['Closed', ''] };
    var list = App.state.windows.slice().sort(function (a, b) { return a.opensAt < b.opensAt ? 1 : -1; });
    document.getElementById('window-list').innerHTML = list.length ? list.map(function (w) {
      var label = labels[App.windowStatus(w)];
      return '<li><div class="row row-between" style="align-items:flex-start">' +
        '<div><strong>' + h(w.title) + '</strong> <span class="badge ' + label[1] + '">' + label[0] + '</span><br>' +
        '<span class="small muted">' + (w.level === 'all' ? 'All levels' : h(w.level) + ' Level') + ' · created by ' + h(w.createdBy) + '</span>' +
        '<dl class="small" style="margin:8px 0 0;display:grid;grid-template-columns:auto 1fr;gap:2px 12px">' +
          '<dt class="muted">Opens</dt><dd style="margin:0">' + App.fmtDateTime(w.opensAt) + '</dd>' +
          '<dt class="muted">Closes</dt><dd style="margin:0">' + App.fmtDateTime(w.closesAt) + '</dd>' +
          '<dt class="muted">Deadline</dt><dd style="margin:0">' + App.fmtDateTime(w.deadline) + '</dd></dl></div>' +
        '<button type="button" class="btn btn-outline btn-sm" data-delete-window="' + h(w.id) + '">Delete</button>' +
        '</div></li>';
    }).join('') : '<li class="muted">No clearance windows scheduled. Students cannot submit requests until one is open.</li>';
  }

  document.getElementById('window-form').addEventListener('submit', function (event) {
    event.preventDefault();
    var f = windowFields;
    var title = f.title.value.trim();
    var opens = f.opens.value ? new Date(f.opens.value) : null;
    var closes = f.closes.value ? new Date(f.closes.value) : null;
    var deadline = f.deadline.value ? new Date(f.deadline.value) : null;
    var errors = {
      title: title ? '' : 'Enter a title for this window.',
      opens: opens ? '' : 'Choose an opening date and time.',
      closes: !closes ? 'Choose a closing date and time.' : (opens && closes <= opens ? 'Closing time must be after the opening time.' : ''),
      deadline: !deadline ? 'Choose a final deadline.' : (closes && deadline < closes ? 'The deadline cannot be before the closing time.' : '')
    };
    var firstInvalid = null;
    ['title', 'opens', 'closes', 'deadline'].forEach(function (key) {
      App.setFieldError(f[key], errors[key]);
      if (errors[key] && !firstInvalid) firstInvalid = f[key];
    });
    if (firstInvalid) { firstInvalid.focus(); return; }

    App.state.windows.push({
      id: 'w' + Date.now(), title: title, level: f.level.value,
      opensAt: opens.toISOString(), closesAt: closes.toISOString(), deadline: deadline.toISOString(),
      createdBy: session.name
    });
    App.save();
    App.audit('Clearance window created', title, f.level.value === 'all' ? 'All levels' : f.level.value + ' Level');
    event.target.reset();
    renderWindows();
    App.toast('Clearance window saved.', 'success');
  });

  document.getElementById('window-list').addEventListener('click', function (event) {
    var button = event.target.closest('[data-delete-window]');
    if (!button) return;
    var win = App.state.windows.find(function (w) { return w.id === button.dataset.deleteWindow; });
    if (!win) return;
    App.confirm({
      title: 'Delete clearance window?',
      message: '"' + win.title + '" will be removed. Students will not be able to submit requests unless another window is open.',
      confirmLabel: 'Delete window',
      danger: true,
      onConfirm: function () {
        App.state.windows.splice(App.state.windows.indexOf(win), 1);
        App.save();
        App.audit('Clearance window deleted', win.title, '');
        renderWindows();
        App.toast('Clearance window deleted.');
      }
    });
  });

  /* ---- Start ----------------------------------------------------------------------------------- */
  App.initTabs(document.getElementById('officer-tabs'));
  renderAll();
  renderWindows();
});
